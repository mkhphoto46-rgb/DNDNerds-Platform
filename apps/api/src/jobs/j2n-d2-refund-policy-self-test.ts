import { strict as assert } from "node:assert";
import { decideSellerOrderRefundScope } from "../refunds/seller-order-refund-policy.js";
import { buildSellerOrderRefundPlan } from "../refunds/seller-order-refund-plan.js";
import { applyRefundClawback } from "../finance/seller-balance-policy.js";

const a = buildSellerOrderRefundPlan({ grossRial: 1_000_000, platformCommissionRial: 50_000, sellerNetRial: 950_000 });
const b = buildSellerOrderRefundPlan({ grossRial: 700_000, platformCommissionRial: 35_000, sellerNetRial: 665_000 });
const c = buildSellerOrderRefundPlan({ grossRial: 300_000, platformCommissionRial: 15_000, sellerNetRial: 285_000 });
assert.equal(a.refundAmountRial + b.refundAmountRial + c.refundAmountRial, 2_000_000);
assert.equal(a.commissionReversalRial, 50_000);
assert.equal(a.sellerNetReversalRial, 950_000);
const first = decideSellerOrderRefundScope({ paymentAmountRial: 2_000_000, alreadyRefundedRial: 0, sellerRefundRial: a.refundAmountRial, providerCanPartialRefund: true });
assert.equal(first.kind, "PARTIAL_PAYMENT");
assert.equal(first.paymentStatus, "PARTIALLY_REFUNDED");
assert.equal(first.paymentAfterRefundRial, 1_000_000);
const second = decideSellerOrderRefundScope({ paymentAmountRial: 2_000_000, alreadyRefundedRial: 1_000_000, sellerRefundRial: b.refundAmountRial, providerCanPartialRefund: true });
assert.equal(second.paymentAfterRefundRial, 1_700_000);
const third = decideSellerOrderRefundScope({ paymentAmountRial: 2_000_000, alreadyRefundedRial: 1_700_000, sellerRefundRial: c.refundAmountRial, providerCanPartialRefund: true });
assert.equal(third.paymentStatus, "REFUNDED");
const single = decideSellerOrderRefundScope({ paymentAmountRial: 400_000, alreadyRefundedRial: 0, sellerRefundRial: 400_000, providerCanPartialRefund: false });
assert.equal(single.kind, "FULL_PAYMENT");
assert.throws(() => decideSellerOrderRefundScope({ paymentAmountRial: 2_000_000, alreadyRefundedRial: 0, sellerRefundRial: 1_000_000, providerCanPartialRefund: false }), /PARTIAL_PROVIDER_UNSUPPORTED/);
assert.throws(() => decideSellerOrderRefundScope({ paymentAmountRial: 2_000_000, alreadyRefundedRial: 1_700_000, sellerRefundRial: 700_000, providerCanPartialRefund: true }), /AMOUNT_INVALID/);
assert.throws(() => decideSellerOrderRefundScope({ paymentAmountRial: 2_000_000, alreadyRefundedRial: 0, sellerRefundRial: -1, providerCanPartialRefund: true }), /AMOUNT_INVALID/);
const original = { pendingRial: 500_000, availableRial: 300_000, negativeRial: 0, paidOutRial: 100_000 };
const adjusted = applyRefundClawback(original, a.sellerNetReversalRial);
assert.deepEqual(adjusted, { pendingRial: 0, availableRial: 0, negativeRial: 150_000, paidOutRial: 100_000 });
assert.deepEqual(original, { pendingRial: 500_000, availableRial: 300_000, negativeRial: 0, paidOutRial: 100_000 });
console.log("J2N-D2 PURE ACCOUNTING / PROVIDER GATE SELF-TEST PASS");
